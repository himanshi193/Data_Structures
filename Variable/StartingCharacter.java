package Variable;

public class StartingCharacter {
    public static void main(String[] args){
        // Starting Character [a,A,_,$]
        // Starting Letter
        int marks = 10;
        int MARKS = 11;
        int _marks = 12;
        int $marks = 13;

        //Subsequent Characters[0 to 9,_,$]

        int height5 = 21;
        int height_love = 33;
        int height$12love = 44;
        int height_ = 22;
        int height$ = 23;
        System.out.println("marks:" + marks);
        System.out.println("MARKS:" + MARKS);
        System.out.println("_marks:" + _marks);
        System.out.println("$marks:" + $marks);
        System.out.println("height5:" + height5);
        System.out.println("height_love:" + height_love);
        System.out.println("height$12love:" + height$12love);
        System.out.println("height_:" + height_);
        System.out.println("height$:" + height$);

    }
}

